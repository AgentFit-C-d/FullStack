package com.agentfit.coreapi.catalog;

import com.agentfit.coreapi.configuration.export.StoredPreviewState;
import com.agentfit.coreapi.configuration.preview.ExistingState;
import com.agentfit.coreapi.configuration.preview.PreviewBasis;
import com.agentfit.coreapi.configuration.preview.PreviewFile;
import com.agentfit.coreapi.configuration.preview.PreviewFingerprintResult;
import com.agentfit.coreapi.recommendation.EnvironmentTarget;
import com.agentfit.coreapi.recommendation.CapabilityKey;
import com.agentfit.coreapi.recommendation.selection.PermissionSelection;
import com.agentfit.coreapi.recommendation.selection.StoredRecommendationState;
import java.util.List;
import java.util.Map;
import java.util.HashMap;
import java.util.Collections;
import java.util.Objects;
import java.util.Set;

/**
 * B's Preview creation boundary. Existing files and generated content stay transient;
 * only content-free metadata crosses the A persistence port.
 */
public final class PreviewCreationService {
    /** A authenticates and checks ownership before returning one consistent current snapshot. */
    public interface TrustedContextReader {
        TrustedContext load(String projectId, String recommendationId);
    }

    /** A rechecks current basis, recommendation, and environment in one save transaction. */
    public interface PreviewStore {
        StoredPreviewState saveIfUnchanged(TrustedContext context, Draft draft);
    }

    /** B2 claims must be restored from the same stored recommendation used for Preview. */
    public record RequiredCapabilities(String recommendationId, PreviewBasis basis,
                                       Set<String> keys) {
        public RequiredCapabilities {
            if (recommendationId == null || recommendationId.isBlank() || basis == null) {
                throw new IllegalArgumentException("required capability source missing");
            }
            keys = Set.copyOf(Objects.requireNonNull(keys));
            if (keys.isEmpty() || !CapabilityKey.keys().containsAll(keys)) {
                throw new IllegalArgumentException("invalid required capabilities");
            }
        }
    }

    public record TrustedContext(PreviewBasis currentBasis, EnvironmentTarget currentTarget,
                                 StoredRecommendationState recommendation,
                                 Map<String, String> installedToolVersions,
                                 RequiredCapabilities requiredCapabilities) {
        public TrustedContext {
            installedToolVersions = Collections.unmodifiableMap(
                new HashMap<>(Objects.requireNonNull(installedToolVersions)));
            Objects.requireNonNull(requiredCapabilities);
            if (recommendation == null
                || !requiredCapabilities.recommendationId().equals(recommendation.recommendationId())
                || !requiredCapabilities.basis().equals(recommendation.basis())) {
                throw new IllegalArgumentException("required capabilities belong to another recommendation");
            }
        }
    }

    /** No generated bytes, supplied originals, or Diff may be persisted from this record. */
    public record Draft(PreviewBasis basis, String recommendationId,
                        List<String> selectedToolKeys, List<PermissionSelection> policies,
                        ExistingState existingState, List<FileMetadata> fileMetadata,
                        String generatorVersion, String selectionDigest,
                        String contentDigest, String fingerprint) {
        public Draft {
            selectedToolKeys = List.copyOf(selectedToolKeys);
            policies = List.copyOf(policies);
            existingState = Objects.requireNonNull(existingState);
            fileMetadata = List.copyOf(fileMetadata);
        }
    }

    /** B8 columns only; configuration content, original bytes and Diff cannot enter the store. */
    public record FileMetadata(String targetKey, String relativePath, PreviewFile.Action action,
                               String beforeHash, String afterHash) {}

    public record Created(StoredPreviewState saved, PreviewFingerprintResult preview,
                          PreviewCapabilityCoverage.Result coverage) {}

    private final TrustedContextReader contexts;
    private final RecommendationCreationService.ApprovedCatalogReader catalogs;
    private final PreviewStore store;

    public PreviewCreationService(TrustedContextReader contexts,
                                  RecommendationCreationService.ApprovedCatalogReader catalogs,
                                  PreviewStore store) {
        this.contexts = Objects.requireNonNull(contexts);
        this.catalogs = Objects.requireNonNull(catalogs);
        this.store = Objects.requireNonNull(store);
    }

    public Created create(String projectId, CatalogPreviewRequest request) {
        if (projectId == null || projectId.isBlank() || request == null
            || request.recommendationId() == null || request.recommendationId().isBlank()) {
            throw new IllegalArgumentException("project and recommendation required");
        }
        TrustedContext context = Objects.requireNonNull(
            contexts.load(projectId, request.recommendationId()));
        if (context.currentBasis() == null
            || !projectId.equals(context.currentBasis().projectId())) {
            throw new IllegalArgumentException("Preview context belongs to another project");
        }
        var catalog = Objects.requireNonNull(catalogs.current());
        CatalogPreviewAssembler.Assembled assembled = CatalogPreviewAssembler.assembleWithCoverage(
            catalog.directory(), catalog.approvedHash(), context.recommendation(),
            context.currentBasis(), context.currentTarget(), request,
            context.installedToolVersions(), context.requiredCapabilities().keys());
        PreviewFingerprintResult preview = assembled.preview();
        Draft draft = new Draft(context.currentBasis(), request.recommendationId(),
            request.selectedToolKeys(), request.permissionSelections(), request.existingState(),
            preview.files().stream().map(file -> new FileMetadata(file.targetKey(),
                file.relativePath(), file.action(), file.beforeHash(), file.afterHash())).toList(),
            request.generatorVersion(), preview.selectionDigest(), preview.contentDigest(),
            preview.fingerprint());
        StoredPreviewState saved = store.saveIfUnchanged(context, draft);
        if (saved == null || saved.previewId() == null || saved.previewId().isBlank()
            || !context.currentBasis().equals(saved.basis())
            || !preview.fingerprint().equals(saved.fingerprint())
            || saved.createdAt() == null || saved.expiresAt() == null
            || !saved.createdAt().isBefore(saved.expiresAt())) {
            throw new IllegalStateException("Preview metadata was not saved correctly");
        }
        return new Created(saved, preview, assembled.coverage());
    }
}

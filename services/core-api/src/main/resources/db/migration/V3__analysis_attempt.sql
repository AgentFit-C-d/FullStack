CREATE TABLE IF NOT EXISTS ANALYSIS_ATTEMPT (
    id BIGSERIAL NOT NULL,
    project_id VARCHAR(36) NOT NULL,
    request_id VARCHAR(128) NOT NULL,
    generation BIGINT NOT NULL,
    contract_version VARCHAR(64) NOT NULL,
    state VARCHAR(32) NOT NULL,
    deadline_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ANALYSIS_ATTEMPT_PK PRIMARY KEY (id),
    CONSTRAINT ANALYSIS_ATTEMPT_PROJECT_FK FOREIGN KEY (project_id) REFERENCES PROJECT (id) ON DELETE CASCADE,
    CONSTRAINT ANALYSIS_ATTEMPT_REQUEST_UQ UNIQUE (request_id),
    CONSTRAINT ANALYSIS_ATTEMPT_GENERATION_CK CHECK (generation >= 1)
);

CREATE INDEX IF NOT EXISTS ANALYSIS_ATTEMPT_PROJECT_IX ON ANALYSIS_ATTEMPT (project_id, generation DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ANALYSIS_ATTEMPT_PROJECT_GENERATION_UQ
    ON ANALYSIS_ATTEMPT (project_id, generation);

ALTER TABLE PROJECT ADD COLUMN IF NOT EXISTS developer_role VARCHAR(32) NOT NULL DEFAULT 'BACKEND';
ALTER TABLE PROJECT ADD COLUMN IF NOT EXISTS current_input_revision BIGINT;

CREATE TABLE IF NOT EXISTS PROJECT_RUNTIME (
    project_id VARCHAR(36) NOT NULL REFERENCES PROJECT(id) ON DELETE CASCADE,
    ordinal INTEGER NOT NULL,
    value VARCHAR(200) NOT NULL,
    normalized_value VARCHAR(200) NOT NULL,
    CONSTRAINT PROJECT_RUNTIME_PK PRIMARY KEY (project_id, ordinal),
    CONSTRAINT PROJECT_RUNTIME_UNQ UNIQUE (project_id, normalized_value)
);

CREATE TABLE IF NOT EXISTS PLANNING_INPUT (
    project_id VARCHAR(36) NOT NULL REFERENCES PROJECT(id) ON DELETE CASCADE,
    revision BIGINT NOT NULL,
    input_type VARCHAR(16) NOT NULL,
    file_name VARCHAR(255),
    media_type VARCHAR(100),
    byte_size BIGINT,
    character_count INTEGER,
    page_count INTEGER,
    raw_content BYTEA,
    extracted_text TEXT,
    citations TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT PLANNING_INPUT_PK PRIMARY KEY (project_id, revision)
);

CREATE TABLE IF NOT EXISTS PROJECT_CREATION_IDEMPOTENCY (
    owner_id BIGINT NOT NULL REFERENCES "USER"(id),
    operation VARCHAR(32) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    project_id VARCHAR(36) REFERENCES PROJECT(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT PROJECT_CREATION_IDEMPOTENCY_PK PRIMARY KEY (owner_id, operation, idempotency_key)
);

CREATE TABLE IF NOT EXISTS ANALYSIS_ADMISSION (
    id SMALLINT PRIMARY KEY,
    active_count SMALLINT NOT NULL CHECK (active_count BETWEEN 0 AND 2),
    updated_at TIMESTAMPTZ NOT NULL
);
INSERT INTO ANALYSIS_ADMISSION(id, active_count, updated_at)
VALUES (1, 0, CURRENT_TIMESTAMP)
ON CONFLICT (id) DO NOTHING;


CREATE TABLE IF NOT EXISTS PROJECT (
    id VARCHAR(36) NOT NULL,
    owner_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    version BIGINT NOT NULL,
    stage VARCHAR(32) NOT NULL,
    analysis_generation BIGINT NOT NULL,
    review_generation BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PROJECT_PK PRIMARY KEY (id),
    CONSTRAINT PROJECT_OWNER_FK FOREIGN KEY (owner_id) REFERENCES "USER" (id),
    CONSTRAINT PROJECT_VERSION_CK CHECK (version >= 1)
);

CREATE INDEX IF NOT EXISTS PROJECT_OWNER_UPDATED_IX ON PROJECT (owner_id, updated_at DESC, id ASC);

CREATE TABLE IF NOT EXISTS AUDIT (
    id BIGSERIAL NOT NULL,
    actor_id BIGINT NOT NULL,
    project_id VARCHAR(36) NOT NULL,
    action VARCHAR(100) NOT NULL,
    result VARCHAR(32) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reason VARCHAR(255),
    CONSTRAINT AUDIT_PK PRIMARY KEY (id),
    CONSTRAINT AUDIT_PROJECT_FK FOREIGN KEY (project_id) REFERENCES PROJECT (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS AUDIT_PROJECT_OCCURRED_IX ON AUDIT (project_id, occurred_at DESC);
